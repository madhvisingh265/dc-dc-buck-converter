"""
Buck converter design calculator.

Given the spec (input, output, load, switching frequency, allowed ripple) it sizes the inductor and
output capacitor, picks the operating mode, and estimates losses and efficiency.

Usage:
    python src/design.py            # prints the design and writes reports/design.md
"""
from dataclasses import dataclass, asdict
from pathlib import Path
import json

ROOT = Path(__file__).resolve().parents[1]


@dataclass
class Spec:
    vin: float = 12.0          # V
    vout: float = 5.0          # V
    iout: float = 1.0          # A (full load)
    fsw: float = 100e3         # Hz
    ripple_i_frac: float = 0.3 # inductor ripple as a fraction of load current
    ripple_v: float = 0.05     # V peak-to-peak output ripple allowed (1% of 5 V)
    # component parameters used for the loss estimate
    rds_on: float = 0.05       # ohm, MOSFET on-resistance (e.g. IRFZ44N class)
    vf_diode: float = 0.45     # V, Schottky forward drop (e.g. 1N5822)
    dcr: float = 0.04          # ohm, inductor winding resistance
    t_sw: float = 50e-9        # s, combined rise+fall time of the switch


def design(s: Spec):
    # Duty cycle including the diode drop: D = (Vout + Vf) / (Vin + Vf)
    D_ideal = s.vout / s.vin
    D = (s.vout + s.vf_diode) / (s.vin + s.vf_diode)
    di = s.ripple_i_frac * s.iout
    L = (s.vin - s.vout) * D / (s.fsw * di)
    C = di / (8 * s.fsw * s.ripple_v)
    i_pk = s.iout + di / 2
    i_rms_L = (s.iout ** 2 + di ** 2 / 12) ** 0.5
    L_crit = (s.vin - s.vout) * D / (2 * s.fsw * s.iout)  # boundary of continuous conduction
    i_min_ccm = di / 2

    p_cond_sw = i_rms_L ** 2 * D * s.rds_on
    p_sw = 0.5 * s.vin * s.iout * s.t_sw * s.fsw * 2
    p_diode = s.vf_diode * s.iout * (1 - D)
    p_dcr = i_rms_L ** 2 * s.dcr
    p_out = s.vout * s.iout
    p_loss = p_cond_sw + p_sw + p_diode + p_dcr
    eff = p_out / (p_out + p_loss)

    return {
        "duty_ideal": D_ideal, "duty_with_diode": D, "inductor_ripple_A": di,
        "L_min_uH": L * 1e6, "C_min_uF": C * 1e6, "inductor_peak_A": i_pk,
        "inductor_rms_A": i_rms_L, "L_critical_uH": L_crit * 1e6,
        "ccm_min_load_A": i_min_ccm,
        "loss_switch_conduction_W": p_cond_sw, "loss_switching_W": p_sw,
        "loss_diode_W": p_diode, "loss_inductor_dcr_W": p_dcr,
        "total_loss_W": p_loss, "efficiency_est": eff,
    }


def main():
    s = Spec()
    r = design(s)
    lines = ["# Design calculations (auto-generated by `src/design.py`)\n", "## Specification\n",
             "| Parameter | Value |", "|---|---|"]
    lines += [f"| {k} | {v:g} |" for k, v in asdict(s).items()]
    lines += ["\n## Results\n", "| Quantity | Value |", "|---|---|"]
    lines += [f"| {k} | {v:.4g} |" for k, v in r.items()]
    lines += ["", "Chosen standard parts: **L = 120 µH** (next standard value above L_min, rated ≥ 1.5 A), **C = 100 µF** electrolytic + 0.1 µF ceramic (≥ C_min, leaves margin for ESR)."]
    (ROOT / "reports").mkdir(exist_ok=True)
    (ROOT / "reports" / "design.md").write_text("\n".join(lines))
    (ROOT / "reports" / "design.json").write_text(json.dumps(r, indent=2))
    print("\n".join(lines))


if __name__ == "__main__":
    main()
